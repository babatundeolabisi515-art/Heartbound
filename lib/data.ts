export function getNovelBySlug(slug: string) {
  return novels.find((n) => n.slug === slug)
}

export function getChapterBySlug(novelSlug: string, chapterId: string) {
  const novel = getNovelBySlug(novelSlug)
  if (!novel) return null
  return novel.chapters.find((c) => c.id === chapterId)
}

export function getChapterIndex(novel: Novel, chapterId: string) {
  return novel.chapters.findIndex((c) => c.id === chapterId)
}
